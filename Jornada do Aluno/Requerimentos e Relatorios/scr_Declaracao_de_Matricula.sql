        CODAPLICACAO,
        ID,
        CODIGO,
        DESCRICAO,
        GUID,
        *
FROM RRPTREPORT
WHERE CODCOLIGADA = 1
AND DESCRICAO LIKE '%DECLARA%'
AND DESCRICAO LIKE '%MATRÍCULA%'

/* PARÂMETROS DE RELATÓRIOS DISPONIBILIZADOS NO EDUCACIONAL/PORTAL
        A tabela que armazena a informação é a SPARAM. 
        No campo MEMO ele retorna todos os códigos dos relatórios disponibilizados. 
        Para Relatórios de Professores o campo ID será 'RELGERADORPROFNET'; 
        para relatórios de Alunos o campo ID será 'RELGERADORALUNONET'. 
        No campo TEXTO ele traz um MEMO de todos os relatórios que já foram disponibilizados.
        Link: https://centraldeatendimento.totvs.com/hc/pt-br/articles/15024936775959-TOTVS-Educacional-Educacional-EDU-Tabela-que-armazena-os-Relat%C3%B3rios-informados-nos-Par%C3%A2metros-Educacionais-de-Portal
*/
SELECT MEMO
FROM SPARAM
WHERE ID = 'RELGERADORALUNONET'


-- LISTA OS RELATÓRIOS DE DECLARAÇÃO DE MATRÍCULA DE ACORDO COM O PARÂMETRO DO EDUCACIONAL/PORTAL
SELECT 
    R.CODAPLICACAO,
    R.CODCOLIGADA,
    P.CODFILIAL,
    P.CODTIPOCURSO,
    R.ID,
    R.CODIGO,
    R.GUID,
    R.DESCRICAO
FROM 
    RRPTREPORT R
    INNER JOIN 
        SPARAM P 
                ON P.MEMO LIKE '%' + CAST(R.Codigo AS NVARCHAR(MAX)) + '%'
WHERE (R.DESCRICAO LIKE '%DECLARA%'
AND R.DESCRICAO LIKE '%MATRÍCULA%')
ORDER BY        R.CODAPLICACAO,
                R.CODCOLIGADA,
                P.CODFILIAL,
                P.CODTIPOCURSO




